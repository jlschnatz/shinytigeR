# Run from the project root: rv run deploy/build.R
#
# Fills deploy/ with everything the server admin needs to build the image:
#   Dockerfile, rproject.toml, rv.lock, shinytigeR_<version>.tar.gz, README.md
# Upload that folder by SFTP; the admin runs the command in README.md.
#
# One image, no separate base image: the package layer (rv sync from rv.lock)
# comes before the app tarball is copied in, so Docker's layer cache reuses it
# until rv.lock changes and a new app version rebuilds in seconds. (The old
# setup's separate base image went stale unnoticed: R 4.3.0 on the server
# while its Dockerfile said 4.5.2, and the missing packages were then compiled
# from CRAN at build time, unpinned.)

R_IMAGE <- "rocker/r-ver:4.6.1" # Ubuntu 24.04 (noble); keep UBUNTU in sync
UBUNTU <- "24.04"
RV_VERSION <- "0.22.0"

pkg_root <- normalizePath(".", mustWork = TRUE)
deploy <- file.path(pkg_root, "deploy")
stopifnot(file.exists(file.path(pkg_root, "DESCRIPTION")))

# ── 1. System dependencies of the locked packages (Posit PPM sysreqs API) ────
lock_text <- readLines(file.path(pkg_root, "rv.lock"))
pkgs <- unique(sub('^name = "([^"]+)".*', "\\1", grep('^name = "', lock_text, value = TRUE)))
message(sprintf("%d packages in rv.lock", length(pkgs)))

query_url <- paste0(
  "https://packagemanager.posit.co/__api__/repos/1/sysreqs?all=false",
  "&distribution=ubuntu&release=", UBUNTU,
  "&pkgname=", paste(pkgs, collapse = "&pkgname=")
)
resp <- jsonlite::fromJSON(url(query_url), simplifyVector = FALSE)
apt <- sort(unique(c("curl", unlist(lapply(
  resp$requirements, function(r) r$requirements$packages
)))))
message("System deps: ", paste(apt, collapse = ", "))

# ── 2. Dockerfile ─────────────────────────────────────────────────────────────
dockerfile <- c(
  "# Generated by deploy/build.R, do not edit by hand. Build: see README.md",
  sprintf("FROM --platform=linux/amd64 %s", R_IMAGE),
  "",
  "# Local time for dates shown to students (calendar, retry time-out).",
  "# R's user cache (bslib/sass compile the theme at startup) goes to /tmp,",
  "# which is always writable. The user has no home directory (admin's block",
  "# below), so HOME points to /tmp too: tools::R_user_dir() resolves ~ even",
  "# when R_USER_CACHE_DIR is set and warned twice per session otherwise.",
  "ENV TZ=Europe/Berlin \\",
  "    HOME=/tmp \\",
  "    R_USER_CACHE_DIR=/tmp/R-cache",
  "",
  "RUN apt-get update -qq && \\",
  "    apt-get install -y --no-install-recommends \\",
  paste0("      ", apt, " \\"),
  "    && rm -rf /var/lib/apt/lists/*",
  "",
  sprintf("ARG RV_VERSION=%s", RV_VERSION),
  "RUN curl -fsSL -o /tmp/rv.tar.gz \\",
  "      https://github.com/A2-ai/rv/releases/download/v${RV_VERSION}/rv-v${RV_VERSION}-x86_64-unknown-linux-gnu.tar.gz && \\",
  "    tar -xzf /tmp/rv.tar.gz -C /usr/local/bin && rm /tmp/rv.tar.gz && rv --version",
  "",
  "# R packages, exactly as in rv.lock. Cached until rv.lock changes.",
  "WORKDIR /srv",
  "COPY rproject.toml rv.lock ./",
  "RUN rv sync --locked && \\",
  "    RVLIB=$(find /srv/rv/library -mindepth 3 -maxdepth 3 -type d | head -1) && \\",
  "    echo \"R_LIBS_USER=$RVLIB\" >> /usr/local/lib/R/etc/Renviron",
  "",
  "# The app itself.",
  "COPY shinytigeR_*.tar.gz /tmp/",
  "RUN R CMD INSTALL /tmp/shinytigeR_*.tar.gz && rm /tmp/shinytigeR_*.tar.gz && \\",
  "    R -q -e 'library(shinytigeR)'",
  "",
  "# The DB folder (SQLite files, reg_code.txt, item images in img_item/) is mounted at /opt/shinyapp.",
  "ENV TIGER_DB_DIR=/opt/shinyapp",
  "",
  "# From here on verbatim from the server admin's Dockerfile, parts of which",
  "# the server requires: user uid 1002 / gid 1003, no home directory (caches",
  "# go to R_USER_CACHE_DIR above), the volume, port and user. Don't change.",
  "RUN chmod o+x /root; addgroup --gid 1003 beitner; adduser --shell /bin/false --no-create-home --uid 1002 --gecos \"Julia Beitner,,,\" --gid 1003 --disabled-password beitner",
  "VOLUME [ \"/opt/shinyapp\" ]",
  "WORKDIR /opt/shinyapp",
  "EXPOSE 3838",
  "USER beitner",
  "CMD [\"R\", \"-q\", \"-e\", \"options(shiny.port = 3838, shiny.host = '0.0.0.0'); shinytigeR::run_app()\"]"
)
writeLines(dockerfile, file.path(deploy, "Dockerfile"))
file.copy(file.path(pkg_root, c("rv.lock", "rproject.toml")), deploy, overwrite = TRUE)

# ── 3. Package tarball ────────────────────────────────────────────────────────
# NAMESPACE is committed; regenerate it first if roxygen2 is available.
if (requireNamespace("roxygen2", quietly = TRUE)) {
  roxygen2::roxygenise(pkg_root)
} else {
  message("roxygen2 not installed: using the committed NAMESPACE")
}
unlink(list.files(deploy, "^shinytigeR_.*\\.tar\\.gz$", full.names = TRUE))
old_wd <- setwd(deploy)
status <- system2(file.path(R.home("bin"), "R"), c("CMD", "build", "--no-build-vignettes", "--no-manual", shQuote(pkg_root)))
setwd(old_wd)
tarball <- list.files(deploy, "^shinytigeR_.*\\.tar\\.gz$")
if (status != 0L || length(tarball) != 1L) stop("R CMD build failed")
message("Built: ", tarball)

# ── 4. README for the admin ───────────────────────────────────────────────────
readme <- c(
  "# shinytigeR: building the image",
  "",
  "Generated by deploy/build.R.",
  "",
  "```",
  "docker build -t shinytiger .",
  "```",
  "",
  "Run it in this folder. Please don't add `--no-cache`: the R packages are",
  "installed in a cached layer that is reused until rv.lock changes, so a new",
  "app version only reinstalls the app (seconds instead of minutes).",
  "",
  "Unchanged from the old image: name `shinytiger`, port 3838, user uid 1002",
  "(gid 1003), DB folder mounted at `/opt/shinyapp`.",
  "",
  "The DB folder must be writable for uid 1002 (the folder itself, not just",
  "the files: SQLite writes journal files next to the databases). It holds",
  "`db_item.sqlite`, `db_user.sqlite`, `db_credentials.sqlite`,",
  "`db_ability.sqlite`, `reg_code.txt` (the semester code for",
  "self-registration) and the subfolder `img_item/` with the item images.",
  "The whole folder needs to be mounted (not single files), so that",
  "`img_item/` is visible in the container too.",
  "",
  "Optional: the semester code can instead be set as the environment variable",
  "`TIGER_REG_CODE` in ShinyProxy's `container-env`; it then takes priority",
  "over `reg_code.txt`.",
  "",
  sprintf("Base image %s, R packages from rv.lock via rv %s.", R_IMAGE, RV_VERSION)
)
writeLines(readme, file.path(deploy, "README.md"))
message("\ndeploy/ is ready to upload: ", paste(list.files(deploy), collapse = ", "))
